/**
 * Launcher-side settings for Lossless Scaling frame generation (LSFG).
 *
 * The frames are generated by the host VulkanRenderer (native LSFG backend)
 * on the composited game output, so DXVK and the game's own swapchain are
 * untouched. The shaders come from Lossless.dll, which the player imports
 * from their own Lossless Scaling purchase; it is never bundled.
 */
internal object FrameGeneration {
    private const val PREFS = "wow_forever"
    private const val KEY_ENABLED = "frame_generation_enabled"
    private const val KEY_MULTIPLIER = "frame_generation_multiplier"

    val MULTIPLIERS = listOf(2, 3, 4)

    fun hasDll(context: Context): Boolean = LsfgVkManager.importedDllFile(context).isFile

    fun enabled(context: Context): Boolean =
        prefs(context).getBoolean(KEY_ENABLED, false) && hasDll(context)

    fun setEnabled(context: Context, enabled: Boolean) {
        prefs(context).edit().putBoolean(KEY_ENABLED, enabled).apply()
    }

    fun multiplier(context: Context): Int =
        prefs(context).getInt(KEY_MULTIPLIER, 2).coerceIn(2, 4)

    fun setMultiplier(context: Context, multiplier: Int) {
        prefs(context).edit().putInt(KEY_MULTIPLIER, multiplier.coerceIn(2, 4)).apply()
    }

    /** Blocking: copies + validates the DLL (builds the shader cache, ~200 ms). */
    fun import(context: Context, uri: Uri, driverName: String?) {
        val input = context.contentResolver.openInputStream(uri) ?: throw IOException("Couldn't open the selected file")
        input.use { LsfgVkManager.importDll(context, it, driverName) }
        setEnabled(context, true)
    }

    fun remove(context: Context) {
        LsfgVkManager.removeImportedDll(context)
        setEnabled(context, false)
    }

    /**
     * Arms or disarms LSFG on the WoW container before launch. The in-game Quick
     * Menu can still change multiplier / flow scale; it persists to the same extras.
     */
    fun applyTo(context: Context, container: Container) {
        val on = enabled(context)
        container.putExtra(LsfgVkManager.EXTRA_ARMED, on.toString())
        container.putExtra(LsfgVkManager.EXTRA_BACKEND, LsfgVkManager.BACKEND_NATIVE)
        if (on) {
            // A launcher change wins over the last in-game value; 0 (= off in the Quick Menu) is reset too.
            container.putExtra(LsfgVkManager.EXTRA_MULTIPLIER, multiplier(context).toString())
        }
    }

    fun label(context: Context): String =
        if (enabled(context)) "Frame Gen: ${multiplier(context)}×" else "Frame Gen: Off"

    private fun prefs(context: Context) = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
}

@Composable
internal fun FrameGenerationDialog(
    hasDll: Boolean,
    enabled: Boolean,
    multiplier: Int,
    isImporting: Boolean,
    onImport: () -> Unit,
    onRemove: () -> Unit,
    onEnabledChange: (Boolean) -> Unit,
    onMultiplierChange: (Int) -> Unit,
    onDismiss: () -> Unit,
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Frame Generation", fontWeight = FontWeight.Bold, fontSize = 17.sp, color = WowGold) },
        text = {
            Column(
                modifier = Modifier.verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                Text(
                    text = "Lossless Scaling frame generation inserts interpolated frames between the ones WoW renders, " +
                        "for smoother motion at the same GPU load. It adds some input latency and can smear UI edges; " +
                        "it works best when the game already holds a steady 30–60 FPS.",
                    fontSize = 13.sp,
                    color = Color(0xFFE2E8F0),
                    lineHeight = 18.sp,
                )
                if (!hasDll) {
                    Text(
                        text = "Needs Lossless.dll from your own copy of Lossless Scaling (Steam). On your PC it's in " +
                            "Steam\\steamapps\\common\\Lossless Scaling\\. Copy it to this device, then import it here.",
                        fontSize = 12.sp,
                        color = WowSubtle,
                        lineHeight = 16.sp,
                    )
                    Button(
                        onClick = onImport,
                        enabled = !isImporting,
                        colors = ButtonDefaults.buttonColors(containerColor = WowBronze, contentColor = Color.White),
                        shape = RoundedCornerShape(10.dp),
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(if (isImporting) "IMPORTING…" else "IMPORT LOSSLESS.DLL", fontWeight = FontWeight.Bold)
                    }
                } else {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text("Enabled", fontSize = 14.sp, color = Color.White, modifier = Modifier.weight(1f))
                        Switch(
                            checked = enabled,
                            onCheckedChange = onEnabledChange,
                            colors = SwitchDefaults.colors(checkedTrackColor = WowBronze),
                        )
                    }
                    Text("Multiplier", fontSize = 13.sp, color = WowMuted)
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        FrameGeneration.MULTIPLIERS.forEach { m ->
                            FilterChip(
                                selected = m == multiplier,
                                onClick = { onMultiplierChange(m) },
                                enabled = enabled,
                                label = { Text("$m×") },
                                colors = FilterChipDefaults.filterChipColors(selectedContainerColor = WowBronze),
                            )
                        }
                    }
                    Text(
                        text = "2× is the sweet spot on Adreno 740/750. Multiplier, flow scale and performance mode " +
                            "can also be changed in-game from the Quick Menu.",
                        fontSize = 11.sp,
                        color = WowSubtle,
                        lineHeight = 15.sp,
                    )
                    Spacer(modifier = Modifier.height(2.dp))
                    Row {
                        OutlinedButton(onClick = onImport, enabled = !isImporting, shape = RoundedCornerShape(10.dp)) {
                            Text(if (isImporting) "IMPORTING…" else "REPLACE DLL", fontSize = 12.sp, color = WowGold)
                        }
                        Spacer(modifier = Modifier.width(8.dp))
                        TextButton(onClick = onRemove, enabled = !isImporting) {
                            Text("REMOVE", fontSize = 12.sp, color = WowMuted)
                        }
                    }
                }
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) { Text("DONE", color = WowGold, fontWeight = FontWeight.Bold) }
        },
    )
}
